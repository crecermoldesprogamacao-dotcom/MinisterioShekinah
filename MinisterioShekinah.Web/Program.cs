string GetConnectionString(string url)
{
    if (url.StartsWith("postgres://") || url.StartsWith("postgresql://"))
    {
        var uri = new Uri(url);
        var userInfo = uri.UserInfo.Split(':');
        int dbPort = uri.Port > 0 ? uri.Port : 5432;

        return $"Host={uri.Host};Port={dbPort};Database={uri.AbsolutePath.TrimStart('/')};Username={userInfo[0]};Password={userInfo[1]};SSL Mode=Require;Trust Server Certificate=true";
    }
    return url;
}

var connectionString = GetConnectionString(rawDatabaseUrl);

// Configuração do banco de dados PostgreSQL com DbContext (Npgsql)
builder.Services.AddDbContext<ShekinahContext>(options =>
    options.UseNpgsql(connectionString));

var app = builder.Build();

// Bloco de autoverificação e criação de tabelas e colunas na nuvem
using (var scope = app.Services.CreateScope())
{
    try
    {
        var services = scope.ServiceProvider;
        var context = services.GetRequiredService<ShekinahContext>();

        // Executa comandos SQL seguros para garantir que todas as tabelas e colunas essenciais existem
        context.Database.ExecuteSqlRaw(@"
            -- 1. Tabela Musicas (com todas as colunas e auto-incremento no Id)
            CREATE TABLE IF NOT EXISTS ""Musicas"" (
                ""Id"" SERIAL PRIMARY KEY,
                ""Titulo"" TEXT,
                ""Artista"" TEXT,
                ""TomOriginal"" TEXT,
                ""Capotraste"" TEXT,
                ""Cifra"" TEXT,
                ""PartituraUrl"" TEXT,
                ""MomentoLiturgico"" TEXT
            );

            -- Garante a coluna MomentoLiturgico caso a tabela já exista
            DO $$ 
            BEGIN 
                IF NOT EXISTS (SELECT 1 FROM information_schema.columns WHERE table_name = 'Musicas' AND column_name = 'MomentoLiturgico') THEN
                    ALTER TABLE ""Musicas"" ADD COLUMN ""MomentoLiturgico"" TEXT;
                END IF;
                IF NOT EXISTS (SELECT 1 FROM information_schema.columns WHERE table_name = 'musicas' AND column_name = 'MomentoLiturgico') THEN
                    ALTER TABLE musicas ADD COLUMN ""MomentoLiturgico"" TEXT;
                END IF;
            END $$;

            -- Garante auto-incremento no Id de Musicas
            BEGIN
                ALTER TABLE ""Musicas"" ALTER COLUMN ""Id"" ADD GENERATED BY DEFAULT AS IDENTITY;
            EXCEPTION WHEN others THEN
                -- Já configurado
            END;

            -- 2. Tabela VelasVirtuais (evita o erro 500 ao acender velas)
            CREATE TABLE IF NOT EXISTS ""VelasVirtuais"" (
                ""Id"" SERIAL PRIMARY KEY,
                ""Nome"" TEXT,
                ""Intencao"" TEXT,
                ""Data"" TIMESTAMP WITHOUT TIME ZONE
            );
        ");

        Console.WriteLine("--> Todas as tabelas e estruturas foram verificadas e criadas com sucesso!");
    }
    catch (Exception ex)
    {
        Console.WriteLine($"--> AVISO NA INICIALIZAÇÃO DO BANCO: {ex.Message}");
    }
}

// 3. Configuração do pipeline de requisições HTTP
